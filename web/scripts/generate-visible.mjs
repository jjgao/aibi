// @ts-check
/**
 * The visible form's ranges (D312, D428): `schemas/visible-form.json`, which the server's export
 * writes from `aibi.core.schema.visible` (the code points its page escapes, under the Unicode
 * version of the Python that wrote it), rendered as `src/api/visible-ranges.ts` within
 * `npm run generate` (`generate:check` fails while it is stale). The file is read strictly: a
 * member missing or of another form, a range out of order, overlapping or outside the code points,
 * a kept member that is no tab, line feed, ZWNJ or ZWJ, or a cut that is not 2,000 fails the
 * generation, so that the page never escapes by a list it misread.
 */

/** The code points the visible form keeps raw, whatever the classes say (D312). */
export const KEPT = [0x09, 0x0a, 0x200c, 0x200d];

/** The cut, in code points (D312). */
export const CUT = 2000;

/** The members of `raw_by_d312` that are ranges. */
const RAW_RANGES = ["default_ignorable_assigned", "default_ignorable_unassigned", "space_separators"];

export class VisibleError extends Error {}

/** @param {unknown} value @returns {value is Record<string, unknown>} */
function isObject(value) {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}

/** @param {unknown} value @returns {value is number} */
function isPoint(value) {
  return typeof value === "number" && Number.isInteger(value) && value >= 0 && value <= 0x10ffff;
}

/**
 * Inclusive ranges, ascending and apart.
 * @param {unknown} value @param {string} at @returns {[number, number][]}
 */
function ranges(value, at) {
  if (!Array.isArray(value)) {
    throw new VisibleError(`${at} is no list`);
  }
  /** @type {[number, number][]} */
  const found = [];
  let after = -1;
  for (const [index, range] of value.entries()) {
    if (!Array.isArray(range) || range.length !== 2 || !isPoint(range[0]) || !isPoint(range[1]) || range[0] > range[1] || range[0] <= after) {
      throw new VisibleError(`${at}[${String(index)}] is no range after the one before it`);
    }
    found.push([range[0], range[1]]);
    after = range[1];
  }
  return found;
}

/** @param {[number, number][]} given @returns {string} */
function written(given) {
  return `Object.freeze([${given.map(([first, last]) => `range(0x${first.toString(16)}, 0x${last.toString(16)})`).join(", ")}])`;
}

/**
 * `src/api/visible-ranges.ts` from the file's text.
 * @param {string} text
 * @returns {string}
 */
export function renderVisible(text) {
  /** @type {unknown} */
  const file = JSON.parse(text);
  if (!isObject(file)) {
    throw new VisibleError("the file is no object");
  }
  const version = file["unidata_version"];
  if (typeof version !== "string" || !/^[0-9]+\.[0-9]+\.[0-9]+$/u.test(version)) {
    throw new VisibleError("unidata_version is no version");
  }
  if (file["cut"] !== CUT) {
    throw new VisibleError(`the cut is not ${String(CUT)}`);
  }
  if (JSON.stringify(file["order"]) !== JSON.stringify(["cut", "fold", "escape"])) {
    throw new VisibleError("the order is not cut, fold, escape");
  }
  if (JSON.stringify(file["kept"]) !== JSON.stringify(KEPT)) {
    throw new VisibleError("the kept members are not tab, line feed, ZWNJ and ZWJ");
  }
  const unsafe = ranges(file["unsafe"], "unsafe");
  const raw = file["raw_by_d312"];
  if (!isObject(raw) || raw["braille_blank"] !== 0x2800) {
    throw new VisibleError("raw_by_d312 is not the record");
  }
  const rows = RAW_RANGES.map((name) => {
    const given = ranges(raw[name], `raw_by_d312.${name}`);
    const count = given.reduce((sum, [first, last]) => sum + last - first + 1, 0);
    if (raw[`${name}_count`] !== count) {
      throw new VisibleError(`raw_by_d312.${name}_count is not its ranges' count`);
    }
    return `  ${name}: ${written(given)},`;
  });
  return `/**
 * Generated by \`scripts/generate-types.mjs\` from \`schemas/visible-form.json\` (the server's
 * \`aibi.core.schema.visible\`): do not edit. Run \`npm run generate\`. The code points the visible
 * form escapes (D312, D428), as inclusive ranges, under the Unicode version of the Python that
 * wrote the file; and what D312 leaves raw (the O-2 record), which the tests render raw.
 */

/** A range, frozen. */
function range(first: number, last: number): readonly [number, number] {
  const pair: [number, number] = [first, last];
  return Object.freeze(pair);
}

/** The Unicode version the ranges were computed under. */
export const UNIDATA_VERSION = "${version}";

/** The code points of a text from data that are shown; the rest is cut and marked. */
export const CUT = ${String(CUT)};

/** The code points that stay raw whatever the classes say: tab, line feed, ZWNJ and ZWJ. */
export const KEPT: readonly number[] = Object.freeze([${KEPT.map((point) => `0x${point.toString(16)}`).join(", ")}]);

/** The unsafe code points (the server's list), as inclusive ranges, ascending. */
export const UNSAFE: readonly (readonly [number, number])[] = ${written(unsafe)};

/** What D312 leaves raw although a renderer may draw it as nothing (D428's O-2 record). */
export const RAW_BY_D312: {
  readonly default_ignorable_assigned: readonly (readonly [number, number])[];
  readonly default_ignorable_unassigned: readonly (readonly [number, number])[];
  readonly space_separators: readonly (readonly [number, number])[];
  readonly braille_blank: number;
} = Object.freeze({
${rows.join("\n")}
  braille_blank: 0x2800,
});
`;
}
